import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { createHash } from 'node:crypto';
import { build } from 'esbuild';

export async function buildPanels() {
  const result = {};
  for (const [kind, file] of [['local', 'panel.js'], ['owner', 'owner-panel.js']]) {
    const bundle = await build({ absWorkingDir: fileURLToPath(new URL('../', import.meta.url)), entryPoints: [fileURLToPath(new URL('../src/ui/' + file, import.meta.url))], bundle: true, write: false, format: 'iife', platform: 'browser', target: 'es2022', logLevel: 'silent' });
    result[kind] = bundle.outputFiles[0].text;
  }
  return '// Generated by scripts/build-panel.mjs. Edit canonical source modules.\nexport const PANEL_SCRIPTS=' + JSON.stringify(result) + ';\n';
}
if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const target = new URL('../src/panel-scripts.generated.mjs', import.meta.url), content = await buildPanels();
  if (process.argv.includes('--check')) {
    if (readFileSync(target, 'utf8') !== content) throw new Error('Panel bundle is stale. Run npm run build:panel.');
  } else writeFileSync(target, content);
  console.log(JSON.stringify({ panelBundles: 2, verified: process.argv.includes('--check'), sha256: createHash('sha256').update(content).digest('hex') }));
}
